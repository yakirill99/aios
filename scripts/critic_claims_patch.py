# Слова, которыми критик описывает действия, которых в решении может не
# быть. Проверяются только те, что однозначно читаются как поступок, а
# не как обсуждение: «закрыли скважину» ловим, «предел обводнённости»
# не трогаем.
_ACTION_CLAIMS = {
    "shut": ("закрыт", "закрыв", "закрыл", "закрытие", "закрытия",
             "останов", "отключ", "вывед из эксплуатации"),
    "cut": ("снижени", "снизил", "придуш", "сократил отбор"),
    "inj": ("перевод под закачку", "переведен под закачку"),
}


def check_claims(text: str, best_tag: str, actions: list | None = None) -> str:
    """
    Отбраковка объяснения, приписывающего решению действия, которых в
    нём нет. Возвращает исходный текст либо пустую строку — вызывающий
    код подставит формулировку, построенную правилами.

    Что считается действием, определяется тегом варианта и списком
    фактических воздействий, а не текстом модели:
      `1_shut`            — закрытие есть, про закрытие писать можно;
      `24_x0p7`, `noop`   — снижение есть / решений нет;
      `PACK_prod_x1p5`    — только форсирование.
    """
    if not text:
        return text
    tag = (best_tag or "").lower()
    low = text.lower()

    controls = {str(getattr(a, "control", "")).upper() for a in (actions or [])}
    has_shut = "shut" in tag or "SHUT" in controls
    # уровень ниже единицы в теге: x0p7 и подобные
    has_cut = "x0" in tag
    has_inj = "inj" in tag or "RATE" in controls

    bad: list[str] = []
    if not has_shut:
        bad += [w for w in _ACTION_CLAIMS["shut"] if w in low]
    if not (has_cut or has_shut):
        bad += [w for w in _ACTION_CLAIMS["cut"] if w in low]
    if not has_inj:
        bad += [w for w in _ACTION_CLAIMS["inj"] if w in low]

    return "" if bad else text


