# ШАГ 2. В методе explain() заменить блок
#
#         res = res or fallback
#         res.explanation = scrub(res.explanation)
#         res.watch = scrub(res.watch)
#         self._trace("critic", {"step": step, "best": best_tag,
#                                "gain": gain_mln, "risk": res.risk,
#                                "explanation": res.explanation})
#
# на следующий. Сигнатуру explain() менять не надо, если список
# фактических воздействий недоступен — проверка работает по тегу.
# ==========================================================================

BLOCK = '''
        res = res or fallback
        res.explanation = scrub(res.explanation)
        res.watch = scrub(res.watch)

        # Объяснение, приписывающее решению не совершённые действия,
        # отбрасывается целиком: лучше сухая формулировка правил, чем
        # правдоподобный вымысел в отчёте для жюри.
        kept = check_claims(res.explanation, best_tag,
                            getattr(self, "_last_actions", None))
        rejected_claim = not kept
        if rejected_claim:
            res.explanation = fallback.explanation

        self._trace("critic", {"step": step, "best": best_tag,
                               "gain": gain_mln, "risk": res.risk,
                               "explanation": res.explanation,
                               "rejected_claim": rejected_claim})
'''

