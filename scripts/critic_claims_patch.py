# Патч критика для agents.py
#
# ЗАЧЕМ. Критик объяснял первый шаг словами про «своевременное закрытие
# скважин», хотя ни одна скважина не закрывалась. На расчёт это не
# влияет — роль критика чисто объяснительная, — но на защите такую
# фразу разберут первой.
#
# ПОЧЕМУ ИМЕННО ТАК. Промпт НЕ трогаем: имя модели и текст запроса
# входят в ключ кэша, и любая правка промпта обесценит llm_cache,
# который лежит в репозитории и на котором держится режим replay.
# Поэтому проверка ставится ПОСЛЕ ответа, рядом со scrub(), который уже
# вычищает выдуманные числа. Получается тот же приём, что и с тегами в
# FR-7.2: не обещание в промпте, а проверяемый фильтр на выходе.
#
